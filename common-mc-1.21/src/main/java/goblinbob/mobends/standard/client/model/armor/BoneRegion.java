/**
 * Enumeration of bone regions for armor vertex assignment.
 */
public enum BoneRegion
{
    HEAD,
    BODY,
    LEFT_ARM_UPPER,
    LEFT_ARM_LOWER,
    RIGHT_ARM_UPPER,
    RIGHT_ARM_LOWER,
    LEFT_LEG_UPPER,
    LEFT_LEG_LOWER,
    RIGHT_LEG_UPPER,
    RIGHT_LEG_LOWER,
    ROOT  // Fallback for unassigned vertices
}
